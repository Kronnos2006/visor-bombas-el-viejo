import assert from 'node:assert/strict';
import {access} from 'node:fs/promises';
import * as T from './public/vendor/three.module.js';
import {photoPumps,componentRows} from './public/equipos-sector.js';
import {exterior,tankSpecs} from './public/sector-fotos.js';
import {readIntegratedPump} from './server.mjs';
const p=id=>photoPumps.find(p=>p.tag===id);
assert.equal(photoPumps.filter(p=>!p.inactive).length,11);
assert.equal(photoPumps.length,12);
assert.equal(new Set(photoPumps.map(p=>p.tag)).size,12);
assert.deepEqual(photoPumps.filter(p=>p.grupo==='lateral').sort((a,b)=>b.z-a.z).map(p=>p.tag),['B23','B25','B24']);
assert.deepEqual(photoPumps.filter(p=>p.grupo==='derecho').sort((a,b)=>b.z-a.z).map(p=>p.tag),['B32','B33','B36']);
assert.deepEqual(photoPumps.filter(p=>p.grupo==='posterior').sort((a,b)=>b.x-a.x).map(p=>p.tag),['B37','B41','B38']);
assert.equal(p('B22').inactive,true);
assert.equal(p('B33').motor.catalogo,'00218XT3E145T');
assert.equal(p('B33').seal.tipo,'Por confirmar');
assert.equal(p('B36').motor.rpm,'1765 rpm');
assert.equal(p('B41').motor.rpm,'3510 rpm');
assert.ok(componentRows(p('B33'),5).some(([k,v])=>k==='Tipo registrado'&&v==='Por confirmar'));
assert.ok(componentRows(p('B24'),5).some(([k,v])=>k==='Tipo registrado'&&v.includes('1.3/8')));
assert.ok(componentRows(p('B36'),2).some(([k,v])=>k==='Impulsor registrado'&&v==='200 mm'));
assert.ok(componentRows(p('B41'),9).some(([k,v])=>k==='Catálogo'&&v==='XJ7P1BM'));
assert.ok(componentRows(p('B33'),7).some(([k,v])=>k==='Pertenencia'&&v.includes('por confirmar')));
const wall=new T.Box3(new T.Vector3(-12.1,0,-9.1),new T.Vector3(12.1,1.1,2.45));
const bounds=[];
for(const pump of photoPumps){
 await access(new URL('./public'+pump.photo,import.meta.url));
 const g=exterior(T,pump.scale,pump.variant);g.rotation.y=pump.rotation;g.position.set(pump.x,.3,pump.z);g.updateMatrixWorld(true);
 const b=new T.Box3().setFromObject(g);bounds.push(b);
 assert.ok(!wall.intersectsBox(b),pump.tag+' invade el área de tanques o muro');
 assert.ok(b.min.x>-16&&b.max.x<16&&b.min.z>-14.5&&b.max.z<12.5,pump.tag+' fuera de plataforma');
 for(const [x,z,r,h] of tankSpecs)assert.ok(!b.intersectsBox(new T.Box3(new T.Vector3(x-r,0,z-r),new T.Vector3(x+r,h,z+r))),pump.tag+' toca tanque');
 const suction=new T.Vector3(0,0,-1).applyAxisAngle(new T.Vector3(0,1,0),pump.rotation);
 assert.ok(suction.dot(new T.Vector3(-pump.x,0,-3.3-pump.z))>0,pump.tag+' succión apunta fuera del sector');
 const integrated=readIntegratedPump(pump.tag);assert.equal(integrated.data.tag,pump.tag);assert.ok(integrated.source.includes(pump.source));
}
for(let i=0;i<bounds.length;i++)for(let j=i+1;j<bounds.length;j++)assert.ok(!bounds[i].intersectsBox(bounds[j]),'Bombas superpuestas');
assert.equal(readIntegratedPump('BOMBA-A'),null);
console.log('OK: 12 posiciones, 11 fichas con datos, orientación hacia tanques, sin colisiones y correspondencia pieza/ficha.');
